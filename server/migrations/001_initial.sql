BEGIN;
CREATE SCHEMA IF NOT EXISTS store;
SET LOCAL search_path TO store, public;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 first_name TEXT NOT NULL, last_name TEXT NOT NULL, email TEXT UNIQUE NOT NULL,
 phone TEXT NOT NULL DEFAULT '', password_hash TEXT NOT NULL,
 role TEXT NOT NULL DEFAULT 'CLIENT' CHECK(role IN ('CLIENT','ADMIN')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS sessions (token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, expires_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS categories (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT UNIQUE NOT NULL, parent_id BIGINT REFERENCES categories(id));
CREATE TABLE IF NOT EXISTS products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, description TEXT NOT NULL DEFAULT '',
 price BIGINT NOT NULL CHECK(price>=0), stock INTEGER NOT NULL DEFAULT 0 CHECK(stock>=0), min_stock INTEGER NOT NULL DEFAULT 5 CHECK(min_stock>=0),
 image TEXT NOT NULL DEFAULT '', category_id BIGINT NOT NULL REFERENCES categories(id), subcategory_id BIGINT REFERENCES categories(id),
 type TEXT NOT NULL DEFAULT 'PRODUCTO' CHECK(type IN ('PRODUCTO','IMPRESION_3D','PERSONALIZADO')),
 active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1)), featured INTEGER NOT NULL DEFAULT 0 CHECK(featured IN (0,1)),
 wholesale_price BIGINT, wholesale_min_quantity INTEGER,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS cart_items (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), product_id BIGINT NOT NULL REFERENCES products(id), quantity INTEGER NOT NULL CHECK(quantity>0), UNIQUE(user_id,product_id));
CREATE TABLE IF NOT EXISTS orders (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), status TEXT NOT NULL DEFAULT 'PENDIENTE' CHECK(status IN ('PENDIENTE','CONFIRMADO','EN_PREPARACION','LISTO','ENTREGADO','CANCELADO')), total BIGINT NOT NULL CHECK(total>=0), created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS order_items (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES orders(id), product_id BIGINT NOT NULL REFERENCES products(id), name TEXT NOT NULL, quantity INTEGER NOT NULL CHECK(quantity>0), unit_price BIGINT NOT NULL CHECK(unit_price>=0), subtotal BIGINT NOT NULL CHECK(subtotal>=0));
CREATE TABLE IF NOT EXISTS quote_requests (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), name TEXT NOT NULL, description TEXT NOT NULL, quantity INTEGER NOT NULL CHECK(quantity>0), reference TEXT NOT NULL DEFAULT '', status TEXT NOT NULL DEFAULT 'PENDIENTE' CHECK(status IN ('PENDIENTE','EN_REVISION','CONTACTADO','CERRADO')), created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE INDEX IF NOT EXISTS idx_orders_user ON orders(user_id);
CREATE INDEX IF NOT EXISTS idx_products_category ON products(category_id);
-- The store schema is private: clients only use the Express API.
REVOKE ALL ON SCHEMA store FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL TABLES IN SCHEMA store FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA store FROM PUBLIC, anon, authenticated;
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE products ENABLE ROW LEVEL SECURITY;
ALTER TABLE cart_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE order_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE quote_requests ENABLE ROW LEVEL SECURITY;
COMMIT;
